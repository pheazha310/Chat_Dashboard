import { z } from "zod";
import { idSchema } from "@shared/utils/ids.js";
import { MAX_TEXT_LENGTH } from "@modules/messages/message.schema.js";
import { applicationIdSchema } from "@modules/conversations/conversation.schema.js";

const clientId = z.string().trim().min(1).max(100);

/** The customer is identified by the token, never by the body: there is deliberately no `customerId` field. */
export const joinBody = z.object({
  /** The loan application the chat is about. Without it the customer's latest open conversation is used. */
  applicationId: applicationIdSchema.optional(),
  subject: z.string().trim().min(1).max(255).optional(),
});
export type JoinInput = z.infer<typeof joinBody>;

export const conversationParams = z.object({ conversationId: idSchema });
export const callParams = z.object({ callId: idSchema });

/** The customer calls the staff of a conversation. */
export const startCallBody = z.object({ callType: z.enum(["AUDIO", "VIDEO"]).default("AUDIO") });
export type StartCallInput = z.infer<typeof startCallBody>;
export const attachmentParams = z.object({ attachmentId: idSchema });
export const messageAudioParams = z.object({ messageId: idSchema });

export const sendBody = z.object({
  /** Generated by the app; resending the same id (e.g. after a timeout) returns the original message. */
  clientId,
  text: z.string().trim().min(1).max(MAX_TEXT_LENGTH),
});
export type SendInput = z.infer<typeof sendBody>;

/** Text fields of the multipart file upload (the file is the `file` part). */
export const fileFields = z.object({
  clientId,
  text: z
    .string()
    .trim()
    .max(MAX_TEXT_LENGTH)
    .optional()
    .transform((value) => value || undefined),
});

export const downloadQuery = z.object({
  inline: z
    .enum(["1", "true", "0", "false"])
    .optional()
    .transform((value) => value === "1" || value === "true"),
});
