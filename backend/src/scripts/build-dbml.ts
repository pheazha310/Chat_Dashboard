/**
 * Joins the per-domain DBML files (docs/database/*.dbml, in file-name order) into docs/database-schema.dbml, the
 * one-file copy that https://dbdiagram.io/d and `@dbml/cli` read (DBML has no imports).
 *
 *   pnpm db:dbml
 *
 * Edit the files in docs/database/, never the generated copy; docs-consistency.test.ts fails when the copy is stale.
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

export const DBML_PARTS_DIR = "docs/database";
export const DBML_OUTPUT = "docs/database-schema.dbml";

const HEADER =
  "// GENERATED by `pnpm db:dbml` from docs/database/*.dbml (one file per domain). Edit those files, not this one.\n\n";

/** The combined DBML for the repository at `root`. */
export function buildDbml(root: string): string {
  const dir = join(root, DBML_PARTS_DIR);
  const parts = readdirSync(dir)
    .filter((name) => name.endsWith(".dbml"))
    .sort()
    .map((name) => readFileSync(join(dir, name), "utf8").trimEnd() + "\n");
  return HEADER + parts.join("\n");
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const root = fileURLToPath(new URL("../../../", import.meta.url));
  writeFileSync(join(root, DBML_OUTPUT), buildDbml(root));
  console.log(`wrote ${DBML_OUTPUT}`);
}
